def generate_qa_response(question, history):
    """生成模拟问答回复"""
    prev_questions = [m['content'] for m in history if m['role'] == 'user']

    for pattern, handler in QA_TEMPLATES:
        if re.search(pattern, question):
            return handler(question)

    if len(prev_questions) >= 2:
        return (
            '你已经问了好几个问题了，让我从另一个角度帮你：\n\n'
            '除了前面讲的方法，还有一个秘诀\u2014\u2014\n'
            '写动物要把动物\u201c当人来写\u201d。\n'
            '比如：它高兴的时候会怎么样？难过的时候呢？生气的时候呢？\n'
            '这样写出来的动物就有了\u201c人味儿\u201d，读起来特别生动！\n\n'
            '还有什么想问的吗？'
        )

    return DEFAULT_QA(question)


