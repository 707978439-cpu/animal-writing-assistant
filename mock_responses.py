# ===== 模板化作文批改 =====
def generate_review(essay):
    """生成模拟作文批改"""
    word_count = len(essay)
    has_shape = any(kw in essay for kw in ['毛', '眼睛', '耳朵', '颜色', '大', '小', '圆'])
    has_habit = any(kw in essay for kw in ['吃', '睡', '玩', '喜欢', '每天'])
    has_feeling = any(kw in essay for kw in ['喜欢', '爱', '开心', '快乐', '朋友', '可爱'])
    has_example = any(kw in essay for kw in ['有一次', '记得', '那天', '一天', '有'])

    score_parts = []
    if has_shape:
        score_parts.append('外形描写比较到位，能观察到动物的基本特征')
    else:
        score_parts.append('外形描写可以更细致一些，建议多观察动物的颜色、大小等特点')

    if has_habit:
        score_parts.append('生活习性写得很清楚，让人了解了这种动物的特点')
    else:
        score_parts.append('可以补充一些生活习性方面的内容，让它更立体')

    if has_feeling:
        score_parts.append('感情表达真挚，能感受到你对这种动物的喜爱')
    else:
        score_parts.append('可以在结尾加上你对它的感情，让作文更有温度')

    if has_example:
        score_parts.append('通过具体事例来写，方法很好，让作文更生动有趣')
    else:
        score_parts.append('建议写一件你和动物之间的小故事，会让作文更吸引人')

    if word_count < 100:
        length_note = '字数偏少，可以再多写一些内容，让描写更加丰富'
    elif word_count < 200:
        length_note = '字数基本达标，继续充实内容会更好'
    else:
        length_note = '篇幅充实，写作态度很认真'

    suggestions = [
        '可以多用比喻句，比如\u201c像\u2026\u2026一样\u201d，让语言更生动',
        '注意段落之间的过渡，可以使用\u201c不但\u2026\u2026而且\u2026\u2026\u201d等关联词',
        '开头可以用一个设问句吸引读者，比如\u201c你见过小猫吗？\u201d',
        '结尾可以表达你的愿望，比如\u201c我希望大家都能保护小动物\u201d',
        '可以加入对话，让作文更有画面感',
        '动词可以更丰富一些，比如\u201c扑、跳、跑、钻\u201d等',
        '可以加一些象声词，如\u201c汪汪\u201d\u201c喵喵\u201d\u201c嗡嗡\u201d等'
    ]
    random.seed(essay)
    selected = random.sample(suggestions, 3)

    review = (
        '【总体分析】\n'
        '这篇习作内容比较完整，写作态度很认真。' + length_note + '。\n\n'
        '【亮点分析】\n'
        + '\u3001'.join(score_parts[:3]) + '\n\n'
        '【改进建议（供教师参考）】\n'
        '1. ' + selected[0] + '\n'
        '2. ' + selected[1] + '\n'
        '3. ' + selected[2] + '\n\n'
        '【字数统计】' + str(word_count) + '字\n\n'
        '\u3010教师须知\u3011以上分析由AI生成，仅供教师参考，'
        '最终评价和建议请教师结合学生实际情况作出。'
        '根据《中小学生成式人工智能使用指南》，'
        '禁止直接使用AI生成内容评价学生。'
    )
    return review


